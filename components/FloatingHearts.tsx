"use client";

import React, { useEffect, useState } from "react";
import { motion } from "framer-motion";

interface HeartItem {
  id: number;
  x: number; // percentage 0-100
  size: number; // size in px
  duration: number; // animation duration in seconds
  delay: number; // delay in seconds
  opacity: number;
  sway: number; // horizontal sway distance
  rotate: number;
  emoji: string;
}

interface FloatingHeartsProps {
  count?: number;
  interactive?: boolean; // click creates a heart
  emojis?: string[];
  opacityRange?: [number, number];
}

const DEFAULT_EMOJIS = ["❤️", "💖", "✨", "🌸", "💕", "🌹", "💘"];

export default function FloatingHearts({
  count = 18,
  interactive = true,
  emojis = DEFAULT_EMOJIS,
}: FloatingHeartsProps) {
  const [hearts, setHearts] = useState<HeartItem[]>([]);
  const [clickedHearts, setClickedHearts] = useState<
    { id: number; x: number; y: number; emoji: string }[]
  >([]);

  useEffect(() => {
    // Generate initial floating elements with deterministic randomness on client
    const generated: HeartItem[] = Array.from({ length: count }, (_, i) => ({
      id: i,
      x: Math.random() * 92 + 4, // 4% to 96%
      size: Math.floor(Math.random() * 14) + 14, // 14px to 28px
      duration: Math.random() * 6 + 7, // 7s to 13s
      delay: Math.random() * 5,
      opacity: Math.random() * 0.4 + 0.35, // 0.35 to 0.75
      sway: (Math.random() - 0.5) * 60,
      rotate: (Math.random() - 0.5) * 45,
      emoji: emojis[Math.floor(Math.random() * emojis.length)],
    }));
    setHearts(generated);
  }, [count, emojis]);

  const handlePointerDown = (e: React.PointerEvent<HTMLDivElement>) => {
    if (!interactive) return;
    const rect = e.currentTarget.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    const newHeart = {
      id: Date.now() + Math.random(),
      x,
      y,
      emoji: emojis[Math.floor(Math.random() * emojis.length)],
    };
    setClickedHearts((prev) => [...prev.slice(-15), newHeart]);
  };

  return (
    <div
      onPointerDown={handlePointerDown}
      className="pointer-events-none absolute inset-0 overflow-hidden select-none z-10"
    >
      {hearts.map((h) => (
        <motion.div
          key={h.id}
          initial={{
            y: "105vh",
            x: `${h.x}%`,
            opacity: 0,
            scale: 0.6,
            rotate: 0,
          }}
          animate={{
            y: "-15vh",
            x: [`${h.x}%`, `${h.x + (h.sway / 10)}%`, `${h.x - (h.sway / 15)}%`, `${h.x}%`],
            opacity: [0, h.opacity, h.opacity, 0],
            scale: [0.6, 1, 1.1, 0.9],
            rotate: [0, h.rotate, -h.rotate, 0],
          }}
          transition={{
            duration: h.duration,
            delay: h.delay,
            repeat: Infinity,
            ease: "easeInOut",
          }}
          style={{
            position: "absolute",
            fontSize: `${h.size}px`,
            filter: "drop-shadow(0 2px 8px rgba(225,29,72,0.3))",
          }}
        >
          {h.emoji}
        </motion.div>
      ))}

      {/* Burst hearts generated by user interaction */}
      {clickedHearts.map((ch) => (
        <motion.div
          key={ch.id}
          initial={{ opacity: 1, scale: 0.4, x: ch.x, y: ch.y }}
          animate={{
            opacity: 0,
            scale: 1.6,
            y: ch.y - 120,
            x: ch.x + (Math.random() - 0.5) * 40,
          }}
          transition={{ duration: 1.2, ease: "easeOut" }}
          style={{
            position: "absolute",
            fontSize: "24px",
            filter: "drop-shadow(0 0 10px rgba(245,208,169,0.8))",
          }}
        >
          {ch.emoji}
        </motion.div>
      ))}
    </div>
  );
}
